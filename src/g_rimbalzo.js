function fromMap(rows, es) {
  const H = rows.length, W = rows[0].length, L = mk(W, H);
  const at = (x, y) => (x < 0 || y < 0 || x >= W || y >= H) ? '#' : rows[y][x];
  const wet = c => c === '~' || c === 'x', stop = c => '#B^v'.includes(c);
  for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) {
    const c = rows[y][x];
    let ch = ' ', w = false;
    if (stop(c)) ch = c;
    else if (c === '~') w = true;
    else if (c === 'x') { ch = '^'; w = true; }
    else if (c !== '.') {
      w = [at(x - 1, y), at(x + 1, y), at(x, y - 1), at(x, y + 1)].filter(wet).length >= 2;
      if (c === 'S') L.start = [x, y];
      else if (c === 'h' || c === 'k') {
        const hz = c === 'h', lim = hz ? '|' : ':';
        const scan = d => { for (let a = (hz ? x : y) + d; ; a += d) { const t = hz ? at(a, y) : at(x, a); if (t === lim) return a + 0.5; if (stop(t)) return a - d + 0.5; } };
        L.e(x + 0.5, y + 0.5, hz ? 'x' : 'y', scan(-1), scan(1), es);
      } else if (OBJ[c]) L.o(OBJ[c], x, y);
    }
    L.g[y][x] = ch; L.wat[y][x] = w;
  }
  return L;
}
