function waterSub(b) {
  const tx = Math.floor(b.x);
  let ty = Math.floor(b.y + b.r * 0.98);
  if (!isWater(tx, ty)) { ty = Math.floor(b.y); if (!isWater(tx, ty)) return 0; }
  while (isWater(tx, ty - 1)) ty--;
  return clamp((b.y + b.r - ty) / (2 * b.r), 0, 1);
}
function overlapRect(b, x0, y0, x1, y1, rr) {
  const nx = clamp(b.x, x0, x1), ny = clamp(b.y, y0, y1);
  return (b.x - nx) ** 2 + (b.y - ny) ** 2 < rr * rr;
}
const dist = (b, x, y) => Math.hypot(b.x - x, b.y - y);

