function collide(b) {
  let jumped = false;
  const x0 = Math.floor(b.x - b.r), x1 = Math.floor(b.x + b.r), y0 = Math.floor(b.y - b.r), y1 = Math.floor(b.y + b.r);
  for (let ty = y0; ty <= y1; ty++) for (let tx = x0; tx <= x1; tx++) {
    const ch = tile(tx, ty);
    if (!isSolid(ch)) continue;
    const px = clamp(b.x, tx, tx + 1), py = clamp(b.y, ty, ty + 1);
    const dx = b.x - px, dy = b.y - py, d2 = dx * dx + dy * dy;
    if (d2 >= b.r * b.r) continue;
    let nx, ny, pen;
    if (d2 < 1e-10) {
      const l = b.x - tx, r = tx + 1 - b.x, t = b.y - ty, bo = ty + 1 - b.y, m = Math.min(l, r, t, bo);
      if (m === t) { nx = 0; ny = -1; } else if (m === bo) { nx = 0; ny = 1; } else if (m === l) { nx = -1; ny = 0; } else { nx = 1; ny = 0; }
      pen = m + b.r;
    } else { const d = Math.sqrt(d2); nx = dx / d; ny = dy / d; pen = b.r - d; }
    b.x += nx * pen; b.y += ny * pen;
    const vn = b.vx * nx + b.vy * ny;
    const ground = ny < -0.6;
    if (ground) b.grounded = true;
    if (vn >= 0) continue;
    if (ground) {
      b.vx -= vn * nx; b.vy -= vn * ny;
      if (-vn > 7) b.sq = Math.min(0.28, -vn / 55);
      if (ch === 'B') {
        if (keys.jump && !jumped) { b.vy = -RUBBER; jumped = true; sfx.boing(); }
        else if (-vn > 2.5) { b.vx += nx * -vn * 0.72; b.vy += ny * -vn * 0.72; sfx.boing(true); }
      } else if (keys.jump && !jumped) { b.vy = -JUMP; jumped = true; sfx.jump(); }
      else if (-vn > 6) { b.vx += nx * -vn * 0.3; b.vy += ny * -vn * 0.3; sfx.thud(-vn); }
    } else {
      const e = 0.2; b.vx -= (1 + e) * vn * nx; b.vy -= (1 + e) * vn * ny;
    }
  }
}

function hazard(b) {
  const x0 = Math.floor(b.x - b.r), x1 = Math.floor(b.x + b.r), y0 = Math.floor(b.y - b.r), y1 = Math.floor(b.y + b.r);
  const rr = b.r * 0.92;
  for (let ty = y0; ty <= y1; ty++) for (let tx = x0; tx <= x1; tx++) {
    const ch = tile(tx, ty);
    if (ch === '^' && overlapRect(b, tx + 0.15, ty + 0.5, tx + 0.85, ty + 1, rr)) return true;
    if (ch === 'v' && overlapRect(b, tx + 0.15, ty, tx + 0.85, ty + 0.5, rr)) return true;
  }
  for (const e of enemies) if (dist(b, e.x, e.y) < b.r + 0.34) return true;
  return false;
}

function objects(b) {
  for (const o of L.objs) {
    if (o.got) continue;
    const cx = o.x + 0.5, cy = o.y + 0.5;
    switch (o.t) {
      case 'ring':
        if (b.x > o.x + 0.12 && b.x < o.x + 0.88 && b.y > o.y && b.y < o.y + 2) {
          o.got = true; ringsGot++; score += 500; sfx.ring(); burst(cx, o.y + 1, '#f6c915', 10, 4);
          if (ringsGot === ringsTotal) { setTimeout(sfx.open, 180); showToast('PORTA APERTA!'); }
          hud();
        }
        break;
      case 'life':
        if (dist(b, cx, cy) < b.r + 0.35) { o.got = true; lives++; score += 1000; sfx.life(); burst(cx, cy, '#ff6b5e', 12, 4); showToast('VITA EXTRA!'); hud(); }
        break;
      case 'cp':
        if (!o.on && dist(b, cx, cy) < b.r + 0.42) {
          o.on = true; respawn = { x: cx, bottom: o.y + 1, big: b.big }; score += 500;
          sfx.cp(); showToast('SALVATO!'); hud();
        }
        break;
      case 'infl':
        if (!b.big && dist(b, cx, cy) < b.r + 0.4) { b.big = true; b.y -= RB - RS; b.r = RB; sfx.infl(); showToast('GONFIATA!'); }
        break;
      case 'defl':
        if (b.big && dist(b, cx, cy) < b.r + 0.35) { b.big = false; b.y += RB - RS; b.r = RS; sfx.defl(); showToast('SGONFIATA!'); }
        break;
      case 'exit':
        if (overlapRect(b, o.x + 0.1, o.y, o.x + 0.9, o.y + 2, b.r)) {
          if (ringsGot >= ringsTotal) { burst(cx, o.y + 1, '#ffd23f', 30, 6); complete(); return; }
          if (doorCD <= 0) { showToast('MANCANO ANELLI!'); doorCD = 2.5; }
        }
        break;
    }
  }
}

function physics(dt) {
  const b = ball;
  keys.left = BTN.left; keys.right = BTN.right; keys.jump = BTN.a || BTN.up;
  const dir = (keys.right ? 1 : 0) - (keys.left ? 1 : 0);
  const sub = waterSub(b);
  if (dir) b.vx += dir * (b.grounded ? ACC_G : ACC_A) * dt;
  else if (b.grounded) { const f = FRIC * dt; b.vx = Math.abs(b.vx) <= f ? 0 : b.vx - Math.sign(b.vx) * f; }
  b.vx = clamp(b.vx, -MAXV, MAXV);
  waterCD -= dt;
  if (sub > 0) {
    const buoy = b.big ? 2.1 : 0.55;
    b.vy += G * (1 - buoy * sub) * dt;
    b.vy *= Math.exp(-2.4 * dt); b.vx *= Math.exp(-0.7 * dt);
    if (!b.big && b.vy > 3) b.vy = 3;
    if (b.big && keys.jump && sub > 0.15 && sub < 0.95 && waterCD <= 0 && b.vy > -3) { b.vy = -JUMP * 0.85; waterCD = 0.5; sfx.jump(); }
  } else b.vy += G * dt;
  if (b.vy > MAXFALL) b.vy = MAXFALL;
  b.x += b.vx * dt; b.y += b.vy * dt;
  b.rot += b.vx * dt / b.r;
  b.grounded = false;
  collide(b);
  objects(b);
}

function burst(x, y, col, n, sp) {
  for (let i = 0; i < n; i++) {
    const a = Math.random() * Math.PI * 2, s = sp * (0.4 + Math.random());
    particles.push({ x, y, vx: Math.cos(a) * s, vy: Math.sin(a) * s - 2, life: 0.6 + Math.random() * 0.5, col, sz: 0.08 + Math.random() * 0.1 });
  }
}

function updateCam(dt, snap) {
  if (!ball || !L) return;
  let tx = ball.x - vw / 2 + clamp(ball.vx * 0.25, -1.5, 1.5), ty = ball.y - vh * 0.55;
  tx = L.W <= vw ? (L.W - vw) / 2 : clamp(tx, 0, L.W - vw);
  ty = L.H <= vh ? (L.H - vh) / 2 : clamp(ty, 0, L.H - vh);
  if (snap) { cam.x = tx; cam.y = ty; }
  else { const k = 1 - Math.exp(-dt * 7); cam.x += (tx - cam.x) * k; cam.y += (ty - cam.y) * k; }
}

function step(dt) {
  time += dt; stateT += dt;
  if (state === 'play') {
    physics(dt);
    if (state === 'play' && hazard(ball)) pop();
  }
  if (state === 'play' || state === 'dead' || state === 'complete') {
    for (const e of enemies) {
      const k = e.axis === 'x' ? 'x' : 'y';
      e[k] += e.dir * e.speed * dt;
      if (e[k] > e.max) { e[k] = e.max; e.dir = -1; }
      if (e[k] < e.min) { e[k] = e.min; e.dir = 1; }
      e.a += dt * 3;
    }
  }
  if (state === 'dead') {
    deadT -= dt;
    if (deadT <= 0) { if (lives <= 0) gameOver(); else { spawnBall(); state = 'play'; } }
  }
  for (const p of particles) { p.x += p.vx * dt; p.y += p.vy * dt; p.vy += 18 * dt; p.life -= dt; }
  if (particles.length) particles = particles.filter(p => p.life > 0);
  if (ball && ball.sq) ball.sq = Math.max(0, ball.sq - dt * 1.6);
  if (state === 'play') updateCam(dt, false);
  if (toast && (toast.t -= dt) <= 0) toast = null;
  if (intro > 0) intro -= dt;
  if (doorCD > 0) doorCD -= dt;
}

